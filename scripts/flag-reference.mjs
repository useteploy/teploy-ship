#!/usr/bin/env node
// Environment flag reference: a generated inventory of every environment key
// the code reads, with where it is read, by which side, its derivable default
// and accepted-value grammar, and a hand-maintained description.
//
// Why this exists: O4 (S19). A flag is an environment key the code reads —
// 160+ of them by late 2026, against the subset docs/DEPLOY.md explains — and
// new ones land every week. Prose cannot keep an inventory honest; this can.
// docs/FLAGS.md is generated from the sources and `--check` fails CI when a
// key the code reads has no row (an undocumented flag) or a row names a key
// nothing reads (a stale row after a rename or removal). Descriptions are the
// one hand-maintained column: regeneration merges them by key, so hand edits
// survive, and the initial fill imports them from docs/DEPLOY.md rows.
//
// What it can see (a static scan of src/**/*.ts, web/src/**/*.ts(x) and
// scripts/*.mjs, excluding *.test.* and src/fixtures/):
//   process.env.KEY and env.KEY member reads; env["KEY"] bracket reads;
//   env[CONST] where CONST is a same-file const string; template reads
//   env[`SHIP_${…}`] (recorded as a pattern row, PREFIX_<...>), including a
//   template assigned to a local or returned by a same-file helper that is
//   then read through env[…]; and call sites of the known env helpers
//   (envFlag, envFlagOff, envCount, envNum, envInt, flagOn) plus same-file
//   local helpers whose body reads env[<their argument>].
//
// What it cannot decide: keys read through indirection it does not resolve —
// a loop variable over an array of literals, or a name built in another
// module — never appear (absent, not wrong). "Side" is a file-location
// heuristic (web/src = web, src and scripts = worker); the web process also
// imports the ship package's enqueue paths, so some "worker" keys are read by
// both processes — docs/DEPLOY.md stays the authority for where to SET a
// flag. Defaults appear only when a literal sits in the read's own fallback
// (?? / || / ternary); everything else says "see source", not a guess.
//
// Usage: node scripts/flag-reference.mjs            # regenerate docs/FLAGS.md
//        node scripts/flag-reference.mjs --check    # CI: fail on drift
//   Options for fixtures: --root DIR --doc FILE

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');

const DOC_HEADER = `# Environment flag reference

<!-- GENERATED by scripts/flag-reference.mjs. Every column except Description is
regenerated from the sources; Description is merged by key, so hand edits
survive regeneration. Regenerate with: node scripts/flag-reference.mjs
CI runs --check and fails when a key the code reads has no row here, or a row
names a key nothing reads. -->

A flag is an environment key the code reads. This table is the generated
inventory of every one the scanner can see in \`src/**/*.ts\`,
\`web/src/**/*.ts(x)\` and \`scripts/*.mjs\` (tests and fixtures excluded);
[DEPLOY.md](DEPLOY.md) remains the prose authority for the model behind the
settings that matter and for where each flag must be set. Columns:

- **Default** — the literal in the read's own fallback (\`??\`, \`||\`, or a
  ternary), when there is one; anything else says "see source".
- **Accepted** — the value grammar the reading code accepts, when it is
  derivable (a known helper, or the comparisons on the read's own line).
  Ship's boolean grammars differ by flag; this column never guesses.
- **Read at** — the first three \`file:line\` sites.
- **Side** — web, worker or both, by file location (\`web/src\` = web). The web
  process also runs the ship package's enqueue paths, so a "worker" key can be
  read by both processes; the Description column says where to SET a flag.
- **Description** — hand-maintained. "TODO" means nobody has written it yet.

Rows named like \`SHIP_EVENT_SECRET_<...>\` are read patterns: the code reads
every key with that prefix, built at runtime.
`;

// Known helper call sites: name -> the value grammar that helper accepts.
// envFlagOff is the off-switch helper used only by flags that default ON, so
// its presence also pins the default (below).
const HELPERS = new Map([
  ['envFlag', '1/true/yes'],
  ['envFlagOff', '0/false/no (flag defaults on)'],
  ['envCount', 'non-negative integer'],
  ['envNum', 'number'],
  ['envInt', 'number'],
  ['flagOn', '1/true/yes/on'],
]);

const TEMPLATE_PREFIX = /^([A-Z][A-Z0-9_]*_)\$\{/;

function walk(dir, out, root) {
  let entries;
  try { entries = readdirSync(dir); } catch { return; }
  for (const name of entries) {
    const p = join(dir, name);
    let st;
    try { st = statSync(p); } catch { continue; }
    if (st.isDirectory()) walk(p, out, root);
    else out.push(relative(root, p).split('\\').join('/'));
  }
}

// The scanner's own source documents the read patterns in comments and
// template strings; scanning it would list `KEY` and `SHIP_<...>` as flags.
const SELF = 'scripts/flag-reference.mjs';

/** The files the scanner reads, in stable order. */
export function sourceFiles(root = REPO) {
  const out = [];
  walk(join(root, 'src'), out, root);
  walk(join(root, 'web/src'), out, root);
  if (statSync(join(root, 'scripts'), { throwIfNoEntry: false })) {
    for (const name of readdirSync(join(root, 'scripts'))) {
      if (!statSync(join(root, 'scripts', name)).isDirectory()) out.push(`scripts/${name}`);
    }
  }
  return out
    .filter(p => /\.(ts|tsx|mjs)$/.test(p))
    .filter(p => !p.includes('.test.'))
    .filter(p => !p.startsWith('src/fixtures/'))
    .filter(p => p.startsWith('src/') || p.startsWith('web/src/') || p.startsWith('scripts/'))
    .filter(p => p !== SELF)
    .sort();
}

const lineAt = (text, i) => text.slice(0, i).split('\n').length;

// Probes look at the read's own line. A fallback literal on another line
// belongs to another key's read: this codebase is full of consecutive
// object-literal properties (`label: env("X") || "Single sign-on",`) where a
// cross-line probe would borrow a neighbour's default. The value grammar,
// though, often sits on the statement AFTER the read (`const v = env.X;
// return v === "on" ? …`), so the accepted-value probe also follows the local
// the read is assigned to on its own line.
const restOfLine = (text, end) => {
  const nl = text.indexOf('\n', end);
  return text.slice(end, nl === -1 ? text.length : nl);
};
const beforeOnLine = (text, start) => {
  const nl = text.lastIndexOf('\n', start);
  return text.slice(nl + 1, start);
};
const farCtx = (text, end) => text.slice(end, end + 400);

function literalText(m) {
  if (m[1] !== undefined) return `"${m[1]}"`;
  if (m[2] !== undefined) return `"${m[2]}"`;
  if (m[3] !== undefined) return m[3];
  return undefined;
}

/** Default from a read's own line: `?? lit`, `|| lit`, or a `? v : lit` tail. */
export function defaultFromContext(ctx) {
  let m = ctx.match(/\?\?\s*(?:"([^"]*)"|'([^']*)'|(-?\d+(?:\.\d+)?))/);
  if (m) return literalText(m);
  m = ctx.match(/\|\|\s*(?:"([^"]*)"|'([^']*)'|(-?\d+(?:\.\d+)?))/);
  if (m) return literalText(m);
  m = ctx.match(/\?\s*[A-Za-z_$][\w$.]*\s*:\s*(?:"([^"]*)"|'([^']*)'|(-?\d+(?:\.\d+)?))\s*[,;)]?\s*$/);
  if (m) return literalText(m);
  return undefined;
}

/** Value grammar from the read's own line: a preceding /re/.test(, === "x", quoted ternaries. */
export function acceptedFromContext(lineAfter, lineBefore = '') {
  const vals = new Set();
  let m = lineBefore.match(/\/\^\(([^)/]+)\)?\$?\/i?\s*\.test\(\s*\(*\s*$/);
  if (m) for (const v of m[1].split('|')) vals.add(v);
  m = lineAfter.match(/\/\^\(([^)/]+)\)?\$?\/i?\s*\.test\(/);
  if (m) for (const v of m[1].split('|')) vals.add(v);
  for (m of lineAfter.matchAll(/===\s*["']([a-z0-9]+)["']/g)) vals.add(m[1]);
  for (m of lineAfter.matchAll(/\?\s*"([a-z0-9]+)"\s*:\s*"([a-z0-9]+)"/g)) { vals.add(m[1]); vals.add(m[2]); }
  return vals.size ? [...vals].sort().join('/') : undefined;
}

// The local a read is assigned to on its own line (`const v = (env.X…` or
// `prop: env("X")`), so the grammar probe can follow `v === "on"` later.
function assignedLocal(text, start) {
  const m = beforeOnLine(text, start).match(/([A-Za-z_$][\w$]*)\s*[:=]\s*[^=;\n]{0,120}$/);
  return m ? m[1] : undefined;
}

// Assignment targets are writes, not reads.
const isAssignment = (text, end) => /^\s*(?:\?\?|\|\||&&)?=[^=]/.test(text.slice(end, end + 6));

/**
 * Scan one file's text. Returns one record per read site:
 * { key, site, parser, def, accepted } (site is "<file>:<line>").
 */
export function scanText(text, file) {
  const out = [];
  const emit = (key, start, end, parser) => {
    if (!key) return;
    const after = restOfLine(text, end);
    let accepted = acceptedFromContext(after, beforeOnLine(text, start));
    // Follow the local this read is assigned to: `v === "on"` one statement
    // later is the key's real grammar.
    const local = assignedLocal(text, end);
    if (local) {
      const far = farCtx(text, end);
      const linked = new Set(accepted ? accepted.split('/') : []);
      // `===` only: `x !== "object"` is a type guard, not a value grammar.
      for (const m of far.matchAll(new RegExp(`\\b${local}\\s*===\\s*["']([a-z0-9]+)["']`, 'g'))) linked.add(m[1]);
      for (const m of far.matchAll(new RegExp(`["']([a-z0-9]+)["']\\s*===\\s*\\b${local}\\b`, 'g'))) linked.add(m[1]);
      if (linked.size) accepted = [...linked].sort().join('/');
    }
    out.push({
      key,
      site: `${file}:${lineAt(text, end)}`,
      parser,
      def: parser === 'envFlagOff' ? 'on' : defaultFromContext(after),
      accepted,
    });
  };

  // Same-file consts: literal strings, and uppercase-prefixed templates that
  // become pattern rows when read through env[CONST].
  const consts = new Map();
  const templateLocals = new Map();
  for (const m of text.matchAll(/(?:^|\n)[ \t]*(?:export\s+)?(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:"([A-Za-z_][\w]*)"|`([^`]*\$\{[^`]*)`)/g)) {
    if (m[2] !== undefined) consts.set(m[1], m[2]);
    else if (m[3] !== undefined) {
      const p = m[3].match(TEMPLATE_PREFIX);
      if (p) templateLocals.set(m[1], `${p[1]}<...>`);
    }
  }

  // Member reads: process.env.KEY (any case) and bare env.KEY (upper-case
  // keys only, so an ExecResult's env.stdout and ".env.example" strings stay
  // out). A "." before env counts only when it follows an identifier
  // (plan.env.X is an env snapshot; ".env.example" is a file name).
  for (const m of text.matchAll(/process\.env\.([A-Za-z_$][\w$]*)/g)) {
    if (!isAssignment(text, m.index + m[0].length)) emit(m[1], m.index, m.index + m[0].length);
  }
  for (const m of text.matchAll(/(?<![\w$])env\.([A-Z][A-Z0-9_]*)/g)) {
    const i = m.index;
    if (text[i - 1] === '.' && !/[\w}$]/.test(text[i - 2] ?? '')) continue;
    if (!isAssignment(text, m.index + m[0].length)) emit(m[1], m.index, m.index + m[0].length);
  }

  // Bracket reads: literals, consts, templates.
  for (const m of text.matchAll(/(?:process\.)?env\[\s*(?:"([^"]+)"|'([^']+)'|`([^`]+)`|([A-Za-z_$][\w$]*))\s*\]/g)) {
    if (m[1] !== undefined || m[2] !== undefined) emit(m[1] ?? m[2], m.index, m.index + m[0].length);
    else if (m[3] !== undefined) {
      const p = m[3].match(TEMPLATE_PREFIX);
      if (p) emit(`${p[1]}<...>`, m.index, m.index + m[0].length);
    } else if (consts.has(m[4])) emit(consts.get(m[4]), m.index, m.index + m[0].length);
    else if (templateLocals.has(m[4])) emit(templateLocals.get(m[4]), m.index, m.index + m[0].length);
  }

  // env[fn(...)] where fn is a same-file function returning an
  // uppercase-prefixed template (mcp.ts secretEnvName -> SHIP_MCP_SECRET_<...>).
  const templateFns = new Map();
  for (const m of text.matchAll(/(?:function\s+([A-Za-z_$][\w$]*)\s*\([^)]*\)[^{]*\{|(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*\([^)]*\)\s*=>)[^{};]*return\s+`([A-Z][A-Z0-9_]*_\$\{[^`]*)`/g)) {
    const p = m[3].match(TEMPLATE_PREFIX);
    if (p) templateFns.set(m[1] ?? m[2], `${p[1]}<...>`);
  }
  for (const m of text.matchAll(/env\[\s*([A-Za-z_$][\w$]*)\(/g)) {
    if (templateFns.has(m[1])) emit(templateFns.get(m[1]), m.index, m.index + m[0].length);
  }

  // Helper call sites. Known names carry their grammar; local helpers whose
  // body reads env[<argument>] are found first so arbitrary names (web's
  // value()/secret()/env()) count too.
  const helperIds = new Set(HELPERS.keys());
  for (const m of text.matchAll(/(?:function\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)[^{]*\{|(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*\(([^)]*)\)\s*=>)/g)) {
    const id = m[1] ?? m[3];
    const params = (m[2] ?? m[4] ?? '').split(',').map(s => s.trim().split(':')[0].split('=')[0].trim()).filter(Boolean);
    const body = text.slice(m.index, m.index + 600);
    if (id && params.some(p => /^[A-Za-z_$][\w$]*$/.test(p) && new RegExp(`env\\[\\s*${p}\\s*\\]`).test(body))) helperIds.add(id);
  }
  for (const id of helperIds) {
    const parser = HELPERS.get(id);
    for (const m of text.matchAll(new RegExp(`\\b${id}\\(\\s*(?:"([A-Z][A-Z0-9_]*)"|'([A-Z][A-Z0-9_]*)')`, 'g'))) {
      emit(m[1] ?? m[2], m.index, m.index + m[0].length, parser);
    }
  }
  return out;
}

/** Scan a root into one entry per key: sites, side, default, accepted. */
export function scanFlags(root = REPO) {
  const entries = new Map();
  for (const file of sourceFiles(root)) {
    let text;
    try { text = readFileSync(join(root, file), 'utf8'); } catch { continue; }
    for (const rec of scanText(text, file)) {
      let e = entries.get(rec.key);
      if (!e) {
        e = { key: rec.key, sites: [], sides: new Set(), defaults: new Set(), accepted: new Set() };
        entries.set(rec.key, e);
      }
      if (!e.sites.includes(rec.site)) e.sites.push(rec.site);
      e.sides.add(file.startsWith('web/') ? 'web' : 'worker');
      if (rec.def !== undefined && !rec.key.endsWith('<...>')) e.defaults.add(rec.def);
      if (rec.parser) e.accepted.add(rec.parser);
      // Context comparisons describe how one concrete key's value is used;
      // for a read pattern (SHIP_X_<...>) they are noise, not a grammar.
      else if (rec.accepted && !rec.key.endsWith('<...>')) e.accepted.add(rec.accepted);
    }
  }
  return entries;
}

const esc = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** One table row; description comes from the merged map, never regenerated. */
export function renderRow(entry, description) {
  const side = entry.sides.has('web') && entry.sides.has('worker') ? 'both' : [...entry.sides][0];
  const sites = entry.sites.slice(0, 3).join(', ');
  const at = entry.sites.length > 3 ? `${sites} (+${entry.sites.length - 3} more)` : sites;
  const def = [...entry.defaults][0] ?? 'see source';
  const accepted = [...entry.accepted].join('; ') || 'see source';
  return `| \`${entry.key}\` | ${esc(def)} | ${esc(accepted)} | ${esc(at)} | ${side} | ${esc(description ?? 'TODO')} |`;
}

/** The whole document from scanned entries plus merged descriptions. */
export function renderFlags(entries, descriptions = new Map()) {
  const L = [DOC_HEADER, '', '| Key | Default | Accepted | Read at | Side | Description |', '| --- | --- | --- | --- | --- | --- |'];
  const keys = [...entries.keys()].sort();
  for (const key of keys) L.push(renderRow(entries.get(key), descriptions.get(key)));
  L.push('');
  const todo = keys.filter(k => !descriptions.has(k) || descriptions.get(k) === 'TODO').length;
  L.push(`${keys.length} keys, ${todo} still described as TODO.`, '');
  return L.join('\n');
}

/** Split a table row into trimmed cells; markdown rows start and end with a pipe. */
const rowCells = line => String(line).split(/(?<!\\)\|/).map(c => c.trim());

/**
 * Parse the Description column back out of a FLAGS.md. Returns a Map key ->
 * description; anything the table still names survives regeneration.
 */
export function parseFlagsDoc(text) {
  const out = new Map();
  for (const line of String(text).split('\n')) {
    const m = line.match(/^\| `([A-Za-z_][\w]*<\.\.\.>|[A-Za-z_][\w]*)` \|/);
    if (!m) continue;
    const cells = rowCells(line).filter(c => c !== '');
    if (cells.length < 6) continue;
    out.set(m[1], cells[cells.length - 1].replace(/\\\|/g, '|'));
  }
  return out;
}

/**
 * Descriptions from docs/DEPLOY.md rows, for the initial fill: a table row
 * whose first cell is one backticked UPPER key (or a comma list of them) and
 * whose last cell is the description. Pattern rows (`SHIP_MCP_SECRET_<NAME>`)
 * match a scanned `PREFIX_<...>` row by prefix.
 */
export function descriptionsFromDeploy(text) {
  const out = new Map();
  // Keys are UPPER; a `<NAME>`-suffixed cell names a read pattern like the
  // scanner's own `PREFIX_<...>` rows.
  const one = '`[A-Z][A-Z0-9_]*(?:<[^`|]+>)?`';
  for (const line of String(text).split('\n')) {
    const m = line.match(new RegExp(`^\\| (${one}(?:, ${one})*) \\|`));
    if (!m) continue;
    const cells = rowCells(line).filter(c => c !== '');
    if (cells.length < 3) continue;
    const desc = cells[cells.length - 1].replace(/\\\|/g, '|');
    for (const k of m[1].split(',').map(s => s.trim().replace(/`/g, ''))) out.set(k, desc);
  }
  return out;
}

/** Merge: FLAGS.md descriptions win, DEPLOY.md fills keys FLAGS.md never described. */
export function mergeDescriptions(entries, docText, deployText = '') {
  const fromDoc = parseFlagsDoc(docText || '');
  const fromDeploy = descriptionsFromDeploy(deployText || '');
  const merged = new Map(fromDoc);
  const fill = (k, v) => {
    if (!merged.has(k) || merged.get(k) === 'TODO') merged.set(k, v);
  };
  for (const [k, v] of fromDeploy) fill(k, v);
  // Pattern rows: a DEPLOY row naming SHIP_X_<NAME> describes the scanned
  // pattern row SHIP_X_<...>.
  for (const key of entries.keys()) {
    if (!key.endsWith('<...>')) continue;
    const prefix = key.slice(0, -5);
    for (const [k, v] of fromDeploy) {
      if (k.startsWith(prefix) && k.includes('<')) { fill(key, v); break; }
    }
  }
  return merged;
}

/**
 * The CI rule: every key the code reads has a row, and every row names a key
 * the code reads. Returns a list of { rule, message }; empty means in sync.
 */
export function checkFlags(entries, docRows) {
  const errors = [];
  for (const key of [...entries.keys()].sort()) {
    if (!docRows.has(key)) {
      errors.push({ rule: 'missing-row', message: `${key} is read by the code but has no row in the flag reference (first read ${entries.get(key).sites[0]})` });
    }
  }
  for (const key of [...docRows.keys()].sort()) {
    if (!entries.has(key)) {
      errors.push({ rule: 'stale-row', message: `${key} has a row but the code no longer reads it (rename, removal, or moved behind unscanned indirection)` });
    }
  }
  return errors;
}

function parseArgs(argv) {
  const o = { root: REPO, doc: join(REPO, 'docs/FLAGS.md') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') o.check = true;
    else if (a === '--root') o.root = resolve(argv[++i]);
    else if (a === '--doc') o.doc = resolve(argv[++i]);
    else throw new Error(`unknown argument ${a}`);
  }
  return o;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let o;
  try { o = parseArgs(process.argv.slice(2)); } catch (e) { console.error(e.message); process.exit(2); }
  const deployPath = join(o.root, 'docs/DEPLOY.md');
  const deployText = existsSync(deployPath) ? readFileSync(deployPath, 'utf8') : '';
  const docText = existsSync(o.doc) ? readFileSync(o.doc, 'utf8') : '';
  const entries = scanFlags(o.root);

  if (o.check) {
    const rows = parseFlagsDoc(docText);
    const errors = checkFlags(entries, rows);
    for (const e of errors) console.error(`FAIL [${e.rule}] ${e.message}`);
    console.log(`${entries.size} keys read by the code, ${rows.size} rows in the reference`);
    process.exit(errors.length ? 1 : 0);
  }

  const merged = mergeDescriptions(entries, docText, deployText);
  writeFileSync(o.doc, renderFlags(entries, merged));
  const todo = [...entries.keys()].filter(k => !merged.has(k) || merged.get(k) === 'TODO').length;
  console.log(`wrote ${o.doc}: ${entries.size} keys, ${todo} TODO descriptions`);
}
